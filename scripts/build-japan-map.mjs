// Generates src/japanMap.js: an outline of Japan's main islands as a single
// SVG path, plus the projection used to place castles on it.
//
// Source: Natural Earth 1:50m via the world-atlas package (public domain).
// Usage: node scripts/build-japan-map.mjs
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const SOURCE = 'https://cdn.jsdelivr.net/npm/world-atlas@2/countries-50m.json';
const JAPAN_ID = '392';

// Main islands down to Yakushima/Tanegashima; the Ryukyu and Ogasawara
// islands would stretch the map far beyond where the clans are.
const BOUNDS = { minLon: 128.5, maxLon: 146.2, minLat: 30.0, maxLat: 45.8 };
const LAT0 = 36; // latitude where horizontal distances are kept true
const WIDTH = 1000;

const outFile = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'src', 'japanMap.js');

const topo = await (await fetch(SOURCE)).json();
const { scale, translate } = topo.transform;

// TopoJSON arcs are delta-encoded integer coordinates
const arcs = topo.arcs.map((arc) => {
  let x = 0;
  let y = 0;
  return arc.map(([dx, dy]) => {
    x += dx;
    y += dy;
    return [x * scale[0] + translate[0], y * scale[1] + translate[1]];
  });
});

function ring(indices) {
  const points = [];
  for (const index of indices) {
    const arc = index < 0 ? arcs[~index].slice().reverse() : arcs[index];
    points.push(...(points.length ? arc.slice(1) : arc));
  }
  return points;
}

const japan = topo.objects.countries.geometries.find((g) => g.id === JAPAN_ID);
const polygons = japan.type === 'Polygon' ? [japan.arcs] : japan.arcs;

const cos0 = Math.cos((LAT0 * Math.PI) / 180);
const k = WIDTH / ((BOUNDS.maxLon - BOUNDS.minLon) * cos0);
const project = (lon, lat) => [(lon - BOUNDS.minLon) * cos0 * k, (BOUNDS.maxLat - lat) * k];
const height = (BOUNDS.maxLat - BOUNDS.minLat) * k;

const inBounds = ([lon, lat]) =>
  lon >= BOUNDS.minLon && lon <= BOUNDS.maxLon && lat >= BOUNDS.minLat && lat <= BOUNDS.maxLat;

let d = '';
let kept = 0;
for (const polygon of polygons) {
  const outer = ring(polygon[0]);
  const centroid = outer.reduce((acc, [x, y]) => [acc[0] + x / outer.length, acc[1] + y / outer.length], [0, 0]);
  if (!inBounds(centroid)) continue;
  for (const rings of polygon) {
    const pts = ring(rings).map(([lon, lat]) => project(lon, lat));
    // Drop points that are visually indistinguishable at this scale
    const simplified = pts.filter((p, i) => {
      if (i === 0 || i === pts.length - 1) return true;
      const q = pts[i - 1];
      return Math.hypot(p[0] - q[0], p[1] - q[1]) > 0.6;
    });
    if (simplified.length < 4) continue;
    d += 'M' + simplified.map(([x, y]) => `${x.toFixed(1)} ${y.toFixed(1)}`).join('L') + 'Z';
    kept++;
  }
}

const out = `// Generated by scripts/build-japan-map.mjs from Natural Earth (public domain).
export const JAPAN_MAP = {
  viewBox: '0 0 ${WIDTH} ${height.toFixed(1)}',
  path: '${d}',
};

const BOUNDS = ${JSON.stringify(BOUNDS)};
const COS0 = ${cos0};
const K = ${k};

// Equirectangular projection matching JAPAN_MAP; returns [x, y] in its viewBox.
export function project(lat, lon) {
  return [(lon - BOUNDS.minLon) * COS0 * K, (BOUNDS.maxLat - lat) * K];
}
`;
fs.writeFileSync(outFile, out);
console.log(`Wrote ${outFile}: ${kept} rings, ${(out.length / 1024).toFixed(1)} KB`);
